import pickle  # Импорт модуля для сериализации и десериализации

def run():   # Функция вывода рез-в: загрузка данных из файла и отображение на экране
    # Протокол обмена: читаем результаты расчетов с обработкой ошибок взаимодействия
    try:
        with open("results.bin", "rb") as f:
            results = pickle.load(f)   # Считываем и восстанавливаем словарь с рез-ми из файла
    except (FileNotFoundError, pickle.PickleError, IOError):
        print("[Ошибка взаимодействия] Файл результатов results.bin поврежден или отсутствует.")
        return False   # Возвращаем false, если файл не удалось прочитать
    
    # Вывод полученных данных в понятном пользователю виде
    print("\n[Модуль вывода] Результаты анализа матрицы:")
    print(f"Кол-во нулей выше главной диагонали: {results['above_main']}")
    print(f"Кол-во нулей ниже главной диагонали: {results['below_main']}")
    print(f"Кол-во нулей выше побочной диагонали: {results['above_side']}")
    print(f"Кол-во нулей ниже побочной диагонали: {results['below_side']}\n")
    return True   # Успешное завершение работы ф-и