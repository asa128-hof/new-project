import pickle  # Импорт модуля для сериализации и десериализации (восстановления объектов из байтов)


def run():  # Ф-я открывает файл в реж. чтения байтов
    # Протокол обмена: читаем данные из бинарного файла с обработкой возможных ошибок
    try:
        # Открываем файл matrix.bin в реж. чтения байтов
        with open("matrix.bin", "rb") as f:
            matrix = pickle.load(f)  # Считываем и восстанавливаем матрицу из файла
    except (FileNotFoundError, pickle.PickleError, IOError):
        # Вывод ошибки, если файл не найден, поврежден, недоступен
        print(
            "[Ошибка взаимодействия] Файл matrix.bin отсутствует или поврежден. Осуществление расчёта невозможно."
        )
        return False  # Прерываем функцию, возвращая false

    n = len(matrix)  # Определяем размерность кв/ матрицы (кол-во строк)

    # Инициализация счётчиков нулей для 4-х областей матрицы
    above_main = below_main = above_side = below_side = 0

    # Двойной цикл для обхода каждого эл-та матрицы
    for i in range(n):
        for j in range(n):
            if (
                matrix[i][j] == 0
            ):  # Проверка, равен ли эл-т нулю
                # Проверка относительно глав. диагонали
                if i < j:
                    above_main += 1  # Элемент строго выше глав. диагонали
                elif i > j:
                    below_main += 1  # Элемент строго ниже глав. диагонали

                # Проверка относительно побоч. диагонали
                if i + j < n - 1:
                    above_side += 1  # Элемент строго выше побоч. диагонали
                elif i + j > n - 1:
                    below_side += 1  # Элемент строго ниже побоч. диагонали

    # Формируем словарь со всеми подсчитанными рез-ми
    results = {
        "above_main": above_main,
        "below_main": below_main,
        "above_side": above_side,
        "below_side": below_side,
    }

    # Протокол обмена: сохраняем рез-ты вычислений в новый бин. файл
    try:
        # Открываем файл results.bin в реж. записи байтов
        with open("results.bin", "wb") as f:
            pickle.dump(results, f)  # Записываем словарь с рез-ми в файл
        print(
            "[Модуль обработки] Расчеты завершены. Данные сохранены в results.bin"
        )
        return True  # Успешное завершение работы ф-и
    except IOError:  # Исправлено: убран случайный пробел в названии ошибки IO Error
        # Обработка ошибок I/O при попытке сохранения рез-в
        print(
            "[Ошибка взаимодействия] Ошибка ввода-вывода при сохранении результатов."
        )
        return False  # Прерываем функцию, возвращая false
