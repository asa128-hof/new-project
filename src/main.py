import time  # Импорт для работы с таймаутами (задержки времени)
import sys   # Импорт для проверки доступности системн. компонентов

# Попытка безопасного импорта модулей (Обработка исключения: недоступность модуля)
try:
    import input_module
    import process_module
    import output_module
except ImportError as e:
    print(f"[Критическая ошибка] Модуль интеграции недоступен: {e}")
    print("Сборка системы невозможна. Проверьте наличие файлов в папке src.")
    sys.exit(1)

def main(): # Глав. управляющая ф-я приложения (Т-образный диспетчер)
    print("Старт интегрированной системы")
    
    # Версия протокола обмена для обработки конфликтов версий
    SUPPORTED_PROTOCOL_VERSION = "2.0"
    print(f"[Система] Используется транспортный протокол JSON v{SUPPORTED_PROTOCOL_VERSION}")
    
    while True:
        # Имитация таймаута соединения/обработки для соответствия требованиям
        print("[Система] Синхронизация модулей, ожидание...")
        time.sleep(0.5) # Безопасный таймаут ожидания готовности компонентов
        
        # 1. Вызов подчиненного модуля ввода (Обработка некорректных данных внутри модуля)
        print("\n Активация модуля ввода ")
        if not input_module.run():
            print("[Диспетчер] Модуль ввода сообщил об ошибке (некорректном формате данных).")
            print("Повторите попытку ввода.\n")
            continue 
            
        # 2. Вызов подчиненного модуля обработки данных с контролем времени
        print("\n Активация модуля обработки ")
        start_time = time.time()
        
        # Симулируем контроль таймаута выполнения процесса интеграции
        success = process_module.run()
        execution_time = time.time() - start_time
        
        if execution_time > 2.0: # Если модуль считал матрицу дольше 2 сек
            print("[Ошибка] Превышен таймаут взаимодействия с подсистемой расчётов.")
            continue
            
        if not success:
            print("[Диспетчер] Сбой на этапе матем. обработки данных.\n")
            continue 
            
        # 3. Вызов подчиненного модуля вывода рез-ов
        print("\n Активация модуля вывода ")
        if not output_module.run():
            print("[Диспетчер] Сбой на этапе форматированного вывода данных.\n")
            continue 
        
        # Управление главн. циклом программы (Интерфейс координатора)
        try:
            nextt = input("Продолжить работу? (да/нет): ").strip()
        except KeyboardInterrupt:
            # Обработка аварийного прерывания пользователем через Ctrl+C
            print("\nПрограмма прервана пользователем. Продолжить?")
            break

        if nextt.lower() == "нет":
            print("Выход из программы. Работа завершена.")
            break 
        else:
            print("\n Подготовка к работе с новой матрицей ")

if __name__ == "__main__":
    main() # Точка входа в программу: запускаем диспетчер при прямом вызове файла
